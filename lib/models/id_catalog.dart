  static List<String> get countries =>
      countryDialCodes.map((c) => c['name']!).toList()..sort();

  static String? dialCodeFor(String? country) {
    if (country == null) return null;
    for (final c in countryDialCodes) {
      if (c['name'] == country) return c['code'];
    }
    return null;
  }

  static List<IdTypeOption> forCountry(String? country) {
    if (country == null || country.isEmpty) return [];
    return byCountry[country] ?? generic;
  }
